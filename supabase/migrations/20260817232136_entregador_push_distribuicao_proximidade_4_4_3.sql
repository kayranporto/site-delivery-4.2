begin;

create extension if not exists pg_net;
create extension if not exists pg_cron;

alter table public.notificacoes
  add column if not exists destino text;

create table if not exists public.entrega_ofertas (
  id bigint generated by default as identity primary key,
  pedido_id uuid not null references public.pedidos(id) on delete cascade,
  entregador_id uuid not null references public.entregadores(id) on delete cascade,
  distancia_coleta_km numeric(10,2),
  valor_oferta numeric(10,2) not null default 0,
  raio_km numeric(10,2),
  etapa smallint not null default 1,
  status text not null default 'disponivel',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (pedido_id, entregador_id),
  constraint entrega_ofertas_distancia_check check (
    distancia_coleta_km is null or distancia_coleta_km between 0 and 5000
  ),
  constraint entrega_ofertas_valor_check check (
    valor_oferta between 0 and 9999.99
  ),
  constraint entrega_ofertas_raio_check check (
    raio_km is null or raio_km between 0 and 5000
  ),
  constraint entrega_ofertas_etapa_check check (etapa between 1 and 3),
  constraint entrega_ofertas_status_check check (
    status in ('disponivel','aceita','encerrada')
  )
);

create index if not exists entrega_ofertas_entregador_status_idx
  on public.entrega_ofertas(entregador_id,status,created_at desc);

create index if not exists entrega_ofertas_pedido_status_idx
  on public.entrega_ofertas(pedido_id,status);

alter table public.entrega_ofertas enable row level security;

drop policy if exists "entregador le ofertas proprias" on public.entrega_ofertas;
create policy "entregador le ofertas proprias"
on public.entrega_ofertas
for select
to authenticated
using (
  entregador_id = (select auth.uid())
  or (select private.is_admin())
);

revoke all on table public.entrega_ofertas from anon, authenticated;
grant select on table public.entrega_ofertas to authenticated;

